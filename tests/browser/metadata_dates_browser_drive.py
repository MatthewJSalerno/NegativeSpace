"""Generated date editing: draft, preview, verified save, replay-safe submission and clear."""
import hashlib
import os
import sys
import time
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

base=sys.argv[1]
with sync_playwright() as p:
    request=p.request.new_context(base_url=base)
    assert request.post('/api/v1/catalog').ok
    def job(mode):
        response=request.post('/api/v1/jobs/start',data={'mode':mode});assert response.ok,response.text()
        for _ in range(600):
            if request.get('/api/v1/jobs/active').json()['active'] is None:return
            time.sleep(.2)
        raise AssertionError('Job did not finish')
    job('index');job('copy')
    listed=request.get('/api/v1/photos?view=organized&q=photo-000.jpg').json()['items']
    photo=listed[0]['id']
    sources={path:hashlib.sha256(path.read_bytes()).hexdigest() for path in Path('/src').glob('photo-000.jpg*')}
    browser=p.chromium.launch();page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[];page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(base+f'/?view=organized&photo={photo}')
    page.get_by_role('tab',name='Metadata',exact=True).click()
    viewer=page.locator('.metadata-sources')
    date_row=viewer.get_by_role('row').filter(has=page.get_by_role('rowheader',name='Date taken',exact=True))
    for width in (1440,720):
        page.set_viewport_size({'width':width,'height':1000})
        # Wait for responsive Inspector remount before scrolling its date action.
        if width <= 800:
            expect(page.get_by_role('dialog',name='Photo details',exact=True)).to_be_visible()
        expect(date_row.get_by_role('button',name='Edit metadata date…',exact=True)).to_be_visible()
        expect(date_row).to_contain_text('2021-02-03 04:05:06')
        date_row.get_by_role('button',name='Edit metadata date…',exact=True).scroll_into_view_if_needed()
        if os.environ.get('SHOTS'):page.screenshot(path=os.environ['SHOTS']+f'/inline-edit-date-{width}.png')
    page.set_viewport_size({'width':1440,'height':1000})
    # Date editing is nested above the expanded Inspector and returns to its Metadata tab.
    page.get_by_role('button',name='Enlarge the photo',exact=True).click()
    expanded=page.locator('.lightbox')
    expect(expanded.get_by_role('tab',name='Metadata',exact=True)).to_have_attribute('aria-selected','true')
    date_row.get_by_role('button',name='Edit metadata date…',exact=True).click()
    nested=page.get_by_role('dialog',name='Edit Date taken',exact=True)
    expect(nested.get_by_label('Date taken',exact=True)).to_have_value('2021-02-03T04:05:06')
    nested.get_by_role('button',name='Cancel',exact=True).click()
    expect(expanded).to_be_visible()
    expect(date_row.get_by_role('button',name='Edit metadata date…',exact=True)).to_be_focused()
    if os.environ.get('SHOTS'):page.screenshot(path=os.environ['SHOTS']+'/expanded-metadata.png')
    expanded.get_by_role('button',name='Close the enlarged photo').click()
    viewer.get_by_role('tab',name='EXIF',exact=True).click()
    expect(viewer.get_by_role('button',name='Edit metadata date…',exact=True)).to_have_count(0)
    viewer.get_by_role('tab',name='XMP Sidecar Primary',exact=True).click()
    date_row.get_by_role('button',name='Edit metadata date…',exact=True).click()
    viewer=page.locator('.metadata-sources')
    expect(page.get_by_role('tab',name='Metadata',exact=True)).to_have_attribute('aria-selected','true')
    dialog=page.get_by_role('dialog',name='Edit Date taken',exact=True)
    field=dialog.get_by_label('Date taken',exact=True)
    expect(field).to_have_value('2021-02-03T04:05:06')
    field.fill('2020-02-31T12:00:00')
    expect(dialog.get_by_role('button',name='Preview change',exact=True)).to_be_disabled()
    field.fill('2012-06-08T00:30:00.123+14:00')
    calendar=dialog.get_by_label('Calendar date',exact=True)
    expect(calendar).to_have_value('2012-06-08')
    calendar.fill('2012-06-07')
    expect(field).to_have_value('2012-06-07T00:30:00.123+14:00')
    # Clearing the helper is not consent to remove recorded metadata.
    calendar.fill('')
    expect(field).to_have_value('2012-06-07T00:30:00.123+14:00')
    if os.environ.get('SHOTS'):page.screenshot(path=os.environ['SHOTS']+'/date-calendar.png')
    dialog.get_by_role('button',name='Cancel',exact=True).click()
    discard=page.get_by_role('alertdialog',name='Discard your unsaved changes?',exact=True)
    discard.get_by_role('button',name='Keep editing',exact=True).click()
    expect(field).to_have_value('2012-06-07T00:30:00.123+14:00')
    dialog.get_by_role('button',name='Preview change',exact=True).click()
    preview=dialog.get_by_role('region',name='Date change preview')
    expect(preview).to_contain_text('library/2012/06/07/photo-000.jpg')
    assert request.get(f'/api/v1/photos/{photo}/date-edit').json()['date']['value']=='2021-02-03T04:05:06'
    for width,theme in ((1440,'light'),(720,'dark')):
        page.set_viewport_size({'width':width,'height':1000})
        page.evaluate('(theme) => document.documentElement.dataset.theme=theme',theme)
        expect(dialog.get_by_role('button',name='Save date and move file',exact=True)).to_be_visible()
        if os.environ.get('SHOTS'):page.screenshot(path=os.environ['SHOTS']+f'/date-preview-{width}.png')
    page.set_viewport_size({'width':1440,'height':1000})
    # Acceptance may be lost after the engine starts. The common submission lookup
    # must find the same request, without submitting a second save.
    def lost_response(route):
        response=route.fetch();assert response.ok,response.text()
        route.abort()
    page.route(f'**/api/v1/photos/{photo}/date-save',lost_response,times=1)
    dialog.get_by_role('button',name='Save date and move file',exact=True).click()
    expect(dialog.get_by_role('heading',name='Date saved',exact=True)).to_be_visible(timeout=30000)
    expect(dialog.locator('footer.settings-actions').get_by_role('button',name='Close',exact=True)).to_be_visible()
    if os.environ.get('SHOTS'):page.screenshot(path=os.environ['SHOTS']+'/date-saved-dialog.png')
    dialog.get_by_role('button',name='Close',exact=True).click()
    assert request.get(f'/api/v1/photos/{photo}/date-edit').json()['date']['value']=='2012-06-07T00:30:00.123+14:00'
    expect(viewer).to_contain_text('2012-06-07 00:30:00.123+14:00')
    viewer.get_by_role('button',name='Edit metadata date…',exact=True).click()
    expect(field).to_have_value('2012-06-07T00:30:00.123+14:00')
    dialog.get_by_role('button',name='Preview change',exact=True).click()
    expect(dialog).to_contain_text('No changes needed')
    expect(dialog.get_by_role('button',name='Save date',exact=True)).to_be_disabled()
    dialog.get_by_role('button',name='Back to edit',exact=True).click()
    draft=field.input_value()
    dialog.get_by_label('Explicitly clear Date taken').check()
    expect(field).to_have_value('')
    expect(calendar).to_have_value('')
    expect(field).to_be_disabled()
    dialog.get_by_label('Explicitly clear Date taken').uncheck()
    expect(field).to_have_value(draft)
    dialog.get_by_label('Explicitly clear Date taken').check()
    dialog.get_by_role('button',name='Preview change',exact=True).click()
    expect(preview).to_contain_text('Explicitly cleared')
    expect(preview).to_contain_text('library/Undated/')
    dialog.get_by_role('button',name='Save date and move file',exact=True).click()
    expect(dialog.get_by_role('heading',name='Date saved',exact=True)).to_be_visible(timeout=30000)
    dialog.get_by_role('button',name='Close',exact=True).click()
    # Repeating a saved explicit clear is a no-op, not another metadata job.
    viewer.get_by_role('button',name='Edit metadata date…',exact=True).click()
    dialog.get_by_label('Explicitly clear Date taken').check()
    dialog.get_by_role('button',name='Preview change',exact=True).click()
    expect(preview).to_contain_text('No changes needed')
    expect(dialog.get_by_role('button',name='Save date',exact=True)).to_be_disabled()
    dialog.get_by_role('button',name='Cancel',exact=True).click()
    discard.get_by_role('button',name='Discard',exact=True).click()
    viewer.get_by_role('tab',name='EXIF',exact=True).click()
    date_row.get_by_role('button',name='Copy date to primary…',exact=True).click()
    expect(dialog).to_contain_text('Copying Date taken from EXIF')
    expect(dialog).to_contain_text('Write to XMP Sidecar')
    dialog.get_by_role('button',name='Preview change',exact=True).click()
    dialog.get_by_role('button',name='Save date and move file',exact=True).click()
    expect(dialog.get_by_role('heading',name='Date saved',exact=True)).to_be_visible(timeout=30000)
    dialog.get_by_role('button',name='Close',exact=True).click()
    # Browser Back must protect a changed draft, including its URL context.
    page.evaluate('history.pushState(null, "", location.href + "&draft_check=1")')
    viewer.get_by_role('button',name='Edit metadata date…',exact=True).click()
    field.fill('2011-01-01T01:01:01')
    page.evaluate('history.back()')
    expect(discard).to_be_visible()
    discard.get_by_role('button',name='Keep editing',exact=True).click()
    expect(field).to_have_value('2011-01-01T01:01:01')
    assert 'draft_check=1' in page.url
    # Closing a changed draft discards only the draft.
    dialog.get_by_role('button',name='Cancel',exact=True).click()
    discard.get_by_role('button',name='Discard',exact=True).click()
    expect(dialog).to_have_count(0)
    assert request.get(f'/api/v1/photos/{photo}/date-edit').json()['date']['value']!='2011-01-01T01:01:01'
    missing=request.get('/api/v1/photos?view=organized&q=photo-001.jpg').json()['items'][0]['id']
    missing_context=request.get(f'/api/v1/photos/{missing}/date-edit').json()
    assert missing_context['target']['kind']=='sidecar_xmp' and not missing_context['date']['present'],missing_context
    page.goto(base+f'/?view=organized&photo={missing}&tab=metadata')
    expect(viewer.get_by_role('row').filter(has=page.get_by_role('rowheader',name='Date taken',exact=True))).to_contain_text('Not recorded')
    expect(viewer).to_contain_text('Primary has no Date taken. A date is recorded in EXIF.')
    viewer.get_by_role('button',name='EXIF',exact=True).click()
    expect(viewer.get_by_role('button',name='Copy date to primary…',exact=True)).to_be_visible()
    viewer.get_by_role('tab',name='XMP Sidecar Primary',exact=True).click()
    viewer.get_by_role('button',name='Edit metadata date…',exact=True).click()
    expect(field).to_have_value('')
    expect(calendar).to_have_value('')
    expect(dialog).to_contain_text('Another source may still supply the filing date.')
    calendar.fill('2010-04-05')
    expect(field).to_have_value('2010-04-05')  # No time or zone is invented.
    draft=field.input_value()
    dialog.get_by_label('Explicitly clear Date taken').check()
    expect(field).to_have_value('')
    expect(calendar).to_have_value('')
    expect(field).to_be_disabled()
    dialog.get_by_label('Explicitly clear Date taken').uncheck()
    expect(field).to_have_value(draft)
    dialog.get_by_label('Explicitly clear Date taken').check()
    expect(calendar).to_be_disabled()
    dialog.get_by_role('button',name='Preview change',exact=True).click()
    expect(preview).to_contain_text('Explicitly cleared')
    expect(preview).to_contain_text('library/Undated/')
    dialog.get_by_role('button',name='Cancel',exact=True).click()
    discard.get_by_role('button',name='Discard',exact=True).click()
    assert request.get(f'/api/v1/photos/{missing}/date-edit').json()==missing_context
    assert all(hashlib.sha256(path.read_bytes()).hexdigest()==digest for path,digest in sources.items())
    # A suspicious year is an advisory in the confirmation, never a save gate.
    before_odd=request.get(f'/api/v1/photos/{photo}/date-edit').json()['date']['value']
    page.goto(base+f'/?view=organized&photo={photo}&tab=metadata')
    viewer.get_by_role('button',name='Edit metadata date…',exact=True).click()
    field.fill('2399-06-07T12:34:56')
    dialog.get_by_role('button',name='Preview change',exact=True).click()
    expect(preview.get_by_role('status')).to_contain_text('This date looks unusual.')
    expect(preview.get_by_role('status')).to_contain_text('ahead of the current year')
    expect(dialog.get_by_role('button',name='Save date and move file',exact=True)).to_be_enabled()
    page.emulate_media(color_scheme='dark')
    page.evaluate("document.documentElement.dataset.theme='dark'")
    for width in (1440,720):
        page.set_viewport_size({'width':width,'height':1000})
        preview.scroll_into_view_if_needed()
        if os.environ.get('SHOTS'):page.screenshot(path=os.environ['SHOTS']+f'/odd-date-preview-{width}.png')
    page.set_viewport_size({'width':1440,'height':1000})
    dialog.get_by_role('button',name='Back to edit',exact=True).click()
    field.fill('2014-01-02T03:04:05')
    dialog.get_by_role('button',name='Preview change',exact=True).click()
    expect(preview.get_by_text('This date looks unusual.',exact=True)).to_have_count(0)
    dialog.get_by_role('button',name='Back to edit',exact=True).click()
    field.fill('2399-06-07T12:34:56')
    dialog.get_by_role('button',name='Preview change',exact=True).click()
    dialog.get_by_role('button',name='Save date and move file',exact=True).click()
    expect(dialog.get_by_role('heading',name='Date saved',exact=True)).to_be_visible(timeout=30000)
    dialog.get_by_role('link',name='View job details',exact=True).click()
    change=page.get_by_role('region',name='Recorded date change')
    expect(change).to_contain_text('Date taken written to XMP Sidecar')
    expect(change).to_contain_text('Before: '+before_odd)
    expect(change).to_contain_text('After: 2399-06-07T12:34:56')
    if os.environ.get('SHOTS'):page.screenshot(path=os.environ['SHOTS']+'/date-job-details.png')
    expect(page.get_by_text('No files were processed.',exact=True)).to_have_count(0)
    expect(page.get_by_text('1 of 1 photo updated',exact=False).first).to_be_visible()
    assert not errors,errors
    browser.close()
print('PASS: date draft, validation, discard, preview/refile, no-change, clear, donor copy, lost acceptance and unchanged source')
